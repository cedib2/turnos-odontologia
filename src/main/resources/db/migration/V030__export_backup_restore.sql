-- Registro de operaciones de exportación, respaldo y restore (C-17).
-- V030 se aplica detrás del tronco base V001-V009; no modifica migraciones aplicadas.
CREATE TABLE export_backup_restore_operacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correlation_id VARCHAR(120) NOT NULL,
    operacion VARCHAR(40) NOT NULL,
    resultado VARCHAR(20) NOT NULL,
    motivo VARCHAR(255),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    tenant_id VARCHAR(80),
    actor_nombre VARCHAR(120),
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_export_operacion_tipo CHECK (
        operacion IN ('EXPORTACION', 'RESPALDO', 'RESTORE')),
    CONSTRAINT ck_export_operacion_resultado CHECK (
        resultado IN ('OK', 'FALLIDO', 'VERIFICADO'))
);

CREATE INDEX ix_export_operacion_correlacion
    ON export_backup_restore_operacion (correlation_id);
CREATE INDEX ix_export_operacion_tenant
    ON export_backup_restore_operacion (tenant_id, registrado_en);

CREATE OR REPLACE FUNCTION export_operacion_rechaza_modificacion() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'registro de operaciones es append-only: operación % rechazada', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_export_operacion_update
    BEFORE UPDATE ON export_backup_restore_operacion
    FOR EACH ROW EXECUTE FUNCTION export_operacion_rechaza_modificacion();

CREATE TRIGGER trg_export_operacion_delete
    BEFORE DELETE ON export_backup_restore_operacion
    FOR EACH ROW EXECUTE FUNCTION export_operacion_rechaza_modificacion();
